import type { AnalysisResult, Issue } from '@server-planner/engine';
import type { Catalog, Endpoint, Project } from '@server-planner/model';
import { formatSize } from '../../app/format';
import { appRows, deviceRows, workloadRows } from '../inventory/rows';
import { ipPlan } from '../ipplan/plan';
import { endpointLabel } from '../simulation/FixDialog';

/** Project documentation as Markdown (EXP-05): inventory, networks, firewall, IP plan, issues. */

const esc = (v: string | number) => String(v).replaceAll('|', '\\|').replaceAll('\n', ' ');
function table(header: string[], rows: (string | number)[][]): string {
  if (rows.length === 0) return '_None._\n';
  return `${[
    `| ${header.map(esc).join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map((c) => esc(c === '' ? '—' : c)).join(' | ')} |`),
  ].join('\n')}\n`;
}

const size = (bytes: number | '') => (bytes === '' || bytes === 0 ? '' : formatSize(bytes));
const endpoint = (project: Project, e: Endpoint) => endpointLabel(project, e);

export function projectMarkdown(
  project: Project,
  catalog: Catalog | null,
  result: AnalysisResult | null,
  describeIssue: (issue: Issue) => string,
  date: string,
): string {
  const out: string[] = [];
  const devices = deviceRows(project, catalog, result);
  const workloads = workloadRows(project, result);
  const apps = appRows(project, catalog);
  out.push(`# ${project.name}`, '', `Generated by Server Planner on ${date}.`, '');
  if (project.description) out.push(project.description, '');
  out.push(
    `- **Devices:** ${devices.length}`,
    `- **Workloads:** ${workloads.length}`,
    `- **Apps:** ${apps.length}`,
    `- **VLANs / subnets:** ${Object.keys(project.vlans).length} / ${Object.keys(project.subnets).length}`,
    `- **Open issues:** ${result ? result.issues.filter((i) => i.severity !== 'info').length : '—'}`,
    '',
  );

  out.push('## Devices', '');
  out.push(
    table(
      ['Name', 'Kind', 'Location', 'Model', 'CPU', 'RAM', 'OS', 'Internet', 'Capacity'],
      devices.map((d) => [
        d.name,
        d.kind,
        d.location,
        d.model,
        d.cpu,
        size(d.memoryBytes),
        d.os,
        d.internet,
        d.capacity,
      ]),
    ),
  );

  out.push('## Workloads', '');
  out.push(
    table(
      ['Name', 'Kind', 'Host', 'vCPU', 'RAM', 'Image / OS'],
      workloads.map((w) => [w.name, w.kind, w.host, w.cpu, size(w.memoryBytes), w.image]),
    ),
  );

  out.push('## Apps', '');
  out.push(
    table(
      ['Name', 'Host', 'Ports', 'Catalog'],
      apps.map((a) => [a.name, a.host, a.ports, a.catalog]),
    ),
  );

  out.push('## Networks', '');
  out.push(
    table(
      ['VLAN', 'Name', 'Subnet', 'Gateway', 'DHCP', 'Zone'],
      Object.values(project.subnets).map((s) => {
        const vlan = s.vlanId ? project.vlans[s.vlanId] : undefined;
        return [
          vlan?.vid ?? '',
          vlan?.name ?? s.name ?? '',
          s.cidr,
          s.gateway ?? '',
          s.dhcp?.enabled ? `${s.dhcp.rangeStart} – ${s.dhcp.rangeEnd}` : '',
          s.zoneId ? (project.zones[s.zoneId]?.name ?? '') : '',
        ];
      }),
    ),
  );

  for (const device of Object.values(project.devices)) {
    if (!device.firewall) continue;
    out.push(
      `## Firewall · ${device.name}`,
      '',
      `Default policy: **${device.firewall.defaultAction}** (first matching rule wins).`,
      '',
    );
    out.push(
      table(
        ['#', 'Action', 'Source', 'Destination', 'Service', 'Note'],
        device.firewall.rules.map((r, i) => [
          i + 1,
          r.enabled ? r.action : `${r.action} (disabled)`,
          endpoint(project, r.source),
          endpoint(project, r.destination),
          r.protocol === 'any'
            ? 'any'
            : `${r.protocol}${r.ports?.length ? `/${r.ports.map((p) => (p.from === p.to ? p.from : `${p.from}-${p.to}`)).join(',')}` : ''}`,
          r.description ?? '',
        ]),
      ),
    );
  }

  out.push('## IP plan', '');
  for (const plan of ipPlan(project)) {
    out.push(`### ${plan.subnet.cidr}${plan.vlan ? ` · VLAN ${plan.vlan}` : ''}`, '');
    out.push(
      table(
        ['Address', 'Host', 'Interface', 'Type'],
        plan.rows.map((r) =>
          r.type === 'address'
            ? [r.ip, r.owner?.name ?? '', r.iface, r.conflict ? `${r.kind} — duplicate` : r.kind]
            : [
                `${r.from} – ${r.to}`,
                '',
                '',
                r.type === 'pool' ? `DHCP pool (${r.count})` : `free (${r.count})`,
              ],
        ),
      ),
    );
  }

  if (result && result.issues.length > 0) {
    out.push('## Issues', '');
    for (const issue of result.issues)
      out.push(`- **${issue.severity}** · ${describeIssue(issue)} (\`${issue.code}\`)`);
    out.push('');
  }
  return `${out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()}\n`;
}
