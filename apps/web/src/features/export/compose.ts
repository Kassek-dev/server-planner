import type { HostRef, Project, Workload } from '@server-planner/model';

/** `docker-compose.yml` for the containers of a host or a stack (EXP-06, SW-13). */

type Container = Workload & { kind: 'container' };

export function containersOf(
  project: Project,
  scope: { host?: HostRef; stackId?: string },
): Container[] {
  return Object.values(project.workloads).filter(
    (w): w is Container =>
      w.kind === 'container' &&
      (scope.stackId
        ? w.stackId === scope.stackId
        : !!scope.host && w.host.type === scope.host.type && w.host.id === scope.host.id),
  );
}

/** Service / volume / network names Compose accepts (starting with a letter or digit). */
const key = (name: string) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9_.-]+/g, '-')
    .replace(/^[.-]+|[.-]+$/g, '') || 'service';
/** Host-side folder of a bind mount: one plain segment, never `.` / `..` (no path traversal). */
const folder = (name: string) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'data';
/**
 * Comments carry user text: keep it on one line. Strips every Unicode control/format character
 * (incl. NEL U+0085, a YAML 1.1 line break) and the line/paragraph separators.
 */
const CONTROL = /[\p{C}\p{Zl}\p{Zp}]+/gu;
const oneLine = (text: string) => text.replace(CONTROL, ' ');
/** Double-quoted YAML scalar (JSON strings are valid YAML). */
const q = (value: string) => JSON.stringify(value);

export function dockerCompose(project: Project, containers: Container[], title: string): string {
  const lines: string[] = [`# ${oneLine(title)} — generated by Server Planner`, 'services:'];
  const volumes = new Set<string>();
  const networks = new Map<string, { driver: string; internal?: boolean }>();
  const taken = new Set<string>();
  for (const c of [...containers].sort((a, b) => a.name.localeCompare(b.name))) {
    let service = key(c.name);
    for (let n = 2; taken.has(service); n += 1) service = `${key(c.name)}-${n}`;
    taken.add(service);
    lines.push(
      `  ${service}:`,
      `    image: ${q(`${c.image}:${c.tag}`)}`,
      `    container_name: ${q(c.name)}`,
      '    restart: unless-stopped',
    );
    if (c.network.mode === 'host') lines.push('    network_mode: host');
    else if (c.network.mode === 'none') lines.push('    network_mode: none');
    else {
      const net = project.dockerNetworks[c.network.dockerNetworkId];
      if (net) {
        const name = key(net.name);
        networks.set(name, { driver: net.driver, ...(net.internal ? { internal: true } : {}) });
        lines.push(
          '    networks:',
          c.network.ip
            ? `      ${name}:\n        ipv4_address: ${q(c.network.ip)}`
            : `      - ${name}`,
        );
      }
    }
    if (c.portMappings.length > 0 && c.network.mode === 'docker-network') {
      lines.push('    ports:');
      for (const m of c.portMappings) {
        const host = m.hostIp ? `${m.hostIp}:${m.hostPort}` : String(m.hostPort);
        lines.push(
          `      - ${q(`${host}:${m.containerPort}${m.protocol === 'udp' ? '/udp' : ''}`)}`,
        );
      }
    }
    if (c.volumes.length > 0) {
      lines.push('    volumes:');
      for (const v of c.volumes) {
        if (v.type === 'named') {
          // Prefix with the service unless the volume name already carries it.
          const name = key(v.name).startsWith(service) ? key(v.name) : key(`${service}-${v.name}`);
          volumes.add(name);
          lines.push(`      - ${q(`${name}:${v.containerPath}`)}`);
        } else {
          const note = v.type === 'bind' ? '' : `  # ${v.type.toUpperCase()} share in the plan`;
          lines.push(`      - ${q(`./${folder(v.name)}:${v.containerPath}`)}${note}`);
        }
      }
    }
    if (c.limits?.cpu !== undefined || c.limits?.memoryBytes !== undefined) {
      lines.push('    deploy:', '      resources:', '        limits:');
      if (c.limits.cpu !== undefined) lines.push(`          cpus: ${q(String(c.limits.cpu))}`);
      if (c.limits.memoryBytes !== undefined)
        lines.push(`          memory: ${Math.round(c.limits.memoryBytes / 1024 ** 2)}M`);
    }
  }
  if (networks.size > 0) {
    lines.push('networks:');
    for (const [name, net] of networks) {
      lines.push(`  ${name}:`, `    driver: ${net.driver}`);
      if (net.internal) lines.push('    internal: true');
    }
  }
  if (volumes.size > 0) {
    lines.push('volumes:');
    for (const name of volumes) lines.push(`  ${name}: {}`);
  }
  return `${lines.join('\n')}\n`;
}
